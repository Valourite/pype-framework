<?php

declare(strict_types=1);

namespace Pype\Tests\Unit;

use PHPUnit\Framework\TestCase;
use Pype\Database\Connection;
use Pype\Database\Migrator;
use Pype\Database\Schema\Schema;
use Pype\Database\Schema\Table;

final class SchemaTest extends TestCase
{
    private static function posts(Table $t): void
    {
        $t->id();
        $t->foreignId('user_id')->constrained()->cascadeOnDelete();
        $t->foreignId('category_id')->nullable()->constrained();
        $t->string('title', 120)->unique();
        $t->text('body')->nullable();
        $t->integer('likes')->default(0)->check('likes >= 0');
        $t->boolean('published')->default(false);
        $t->json('meta')->nullable();
        $t->timestamps();
        $t->index(['user_id', 'created_at']);
    }

    /** No server needed: the grammar only needs the driver name. */
    private function sqlFor(string $driver): string
    {
        $db = $driver === 'sqlite' ? Connection::sqlite() : new Connection(['driver' => $driver, 'database' => 'x']);

        return (new Schema($db))->toSql('posts', self::posts(...));
    }

    public function test_sqlite_sql(): void
    {
        $sql = $this->sqlFor('sqlite');

        $this->assertStringContainsString('"id" INTEGER PRIMARY KEY AUTOINCREMENT', $sql);
        $this->assertStringContainsString('"user_id" INTEGER NOT NULL', $sql);
        $this->assertStringContainsString('"title" VARCHAR(120) NOT NULL UNIQUE', $sql);
        $this->assertStringContainsString('"likes" INTEGER NOT NULL DEFAULT 0 CHECK (likes >= 0)', $sql);
        $this->assertStringContainsString('"published" INTEGER NOT NULL DEFAULT 0', $sql);
        $this->assertStringContainsString('"created_at" TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP', $sql);
        $this->assertStringContainsString('FOREIGN KEY ("user_id") REFERENCES "users" ("id") ON DELETE CASCADE', $sql);
        $this->assertStringContainsString('FOREIGN KEY ("category_id") REFERENCES "categories" ("id")', $sql);
        $this->assertStringContainsString('CREATE INDEX "posts_user_id_created_at_index" ON "posts" ("user_id", "created_at")', $sql);
    }

    public function test_mysql_sql(): void
    {
        $sql = $this->sqlFor('mysql');

        $this->assertStringContainsString('`id` BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY', $sql);
        $this->assertStringContainsString('`user_id` BIGINT UNSIGNED NOT NULL', $sql);
        $this->assertStringContainsString('`published` TINYINT(1) NOT NULL DEFAULT 0', $sql);
        $this->assertStringContainsString('`meta` JSON NULL', $sql);
        $this->assertStringContainsString('`created_at` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP', $sql);
        $this->assertStringContainsString('ENGINE=InnoDB DEFAULT CHARSET=utf8mb4', $sql);
    }

    public function test_pgsql_sql(): void
    {
        $sql = $this->sqlFor('pgsql');

        $this->assertStringContainsString('"id" BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY', $sql);
        $this->assertStringContainsString('"user_id" BIGINT NOT NULL', $sql);
        $this->assertStringContainsString('"published" BOOLEAN NOT NULL DEFAULT FALSE', $sql);
        $this->assertStringContainsString('"meta" JSONB NULL', $sql);
        $this->assertStringContainsString('"created_at" TIMESTAMP(0) NOT NULL DEFAULT CURRENT_TIMESTAMP', $sql);
    }

    public function test_string_defaults_are_escaped(): void
    {
        $build = fn (Table $t) => $t->string('s')->default("it's a \\ test");

        $this->assertStringContainsString("DEFAULT 'it''s a \\ test'", (new Schema(Connection::sqlite()))->toSql('t', $build));
        $this->assertStringContainsString("DEFAULT 'it''s a \\\\ test'", (new Schema(new Connection(['driver' => 'mysql', 'database' => 'x'])))->toSql('t', $build));
    }

    public function test_create_and_alter_run_on_sqlite(): void
    {
        $db = Connection::sqlite();
        $schema = new Schema($db);
        $schema->create('users', function (Table $t) {
            $t->id();
            $t->string('name');
        });
        $schema->create('categories', fn (Table $t) => $t->id());
        $schema->create('posts', self::posts(...));

        $userId = (int) $db->table('users')->insert(['name' => 'Ada']);
        $postId = (int) $db->table('posts')->insert(['user_id' => $userId, 'title' => 'Hi']);
        $post = $db->table('posts')->where('id', $postId)->first();
        $this->assertSame(0, $post['likes']);
        $this->assertNotNull($post['created_at']);

        $schema->table('posts', function (Table $t) {
            $t->string('slug')->nullable();
            $t->foreignId('editor_id')->nullable()->constrained('users')->nullOnDelete();
            $t->renameColumn('body', 'content');
            $t->index('slug');
        });
        $db->table('posts')->where('id', $postId)->update(['slug' => 'hi', 'content' => 'text', 'editor_id' => $userId]);
        $this->assertSame('text', $db->table('posts')->where('slug', 'hi')->value('content'));

        // Foreign keys are enforced.
        $db->table('users')->where('id', $userId)->delete();
        $this->assertSame(0, $db->table('posts')->count());

        $schema->table('posts', fn (Table $t) => $t->dropIndex('posts_slug_index')->dropColumn('slug'));
        $this->assertArrayNotHasKey('slug', $db->first('SELECT * FROM posts') ?? ['x' => 1]);
        $schema->dropIfExists('posts');
        $this->assertNull($db->scalar("SELECT name FROM sqlite_master WHERE name = 'posts'"));
    }

    public function test_migrator_runs_php_and_sql_files_in_name_order(): void
    {
        $dir = sys_get_temp_dir() . '/pype-mig-' . bin2hex(random_bytes(4));
        mkdir($dir);
        file_put_contents("{$dir}/2026_01_01_000000_create_users_table.php", <<<'PHP'
            <?php
            use Pype\Database\Schema\{Migration, Schema, Table};
            return new class extends Migration {
                public function up(Schema $schema): void
                {
                    $schema->create('users', function (Table $t) {
                        $t->id();
                        $t->string('email')->unique();
                    });
                }
            };
            PHP);
        file_put_contents("{$dir}/2026_01_02_000000_seed_admin.sql", "INSERT INTO users (email) VALUES ('admin@x.test');");

        $db = Connection::sqlite();
        $migrator = new Migrator($db, $dir);
        $this->assertSame(['2026_01_01_000000_create_users_table', '2026_01_02_000000_seed_admin'], $migrator->migrate());
        $this->assertSame([], $migrator->migrate());
        $this->assertSame('admin@x.test', $db->table('users')->value('email'));

        // Converting a .sql migration to .php keeps its name, so it doesn't run again.
        rename("{$dir}/2026_01_02_000000_seed_admin.sql", "{$dir}/2026_01_02_000000_seed_admin.php");
        file_put_contents("{$dir}/2026_01_02_000000_seed_admin.php", '<?php return new class extends Pype\Database\Schema\Migration { public function up(Pype\Database\Schema\Schema $s): void { throw new LogicException("ran again"); } };');
        $this->assertSame([], $migrator->migrate());

        array_map('unlink', glob("{$dir}/*"));
        rmdir($dir);
    }

    public function test_long_text_is_longtext_only_on_mysql(): void
    {
        $sql = fn (string $driver) => (new Schema($driver === 'sqlite' ? Connection::sqlite() : new Connection(['driver' => $driver, 'database' => 'x'])))
            ->toSql('cache', fn (Table $t) => $t->longText('value'));

        $this->assertStringContainsString('"value" TEXT NOT NULL', $sql('sqlite'));
        $this->assertStringContainsString('`value` LONGTEXT NOT NULL', $sql('mysql'));
        $this->assertStringContainsString('"value" TEXT NOT NULL', $sql('pgsql'));
    }
}
