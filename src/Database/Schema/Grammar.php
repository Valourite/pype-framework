<?php

declare(strict_types=1);

namespace Pype\Database\Schema;

use Pype\Database\Connection;

/** Turns a Table into SQL for sqlite, mysql or pgsql. Only used at migrate time. */
final class Grammar
{
    private readonly string $driver;

    public function __construct(private readonly Connection $db)
    {
        $this->driver = $db->driver();
    }

    /** @return list<string> */
    public function create(Table $table): array
    {
        $lines = array_map($this->column(...), $table->columns);

        // Table-level foreign keys: MySQL silently ignores the inline REFERENCES form.
        foreach ($table->columns as $column) {
            if ($column->references !== null) {
                $lines[] = $this->foreignKey($column);
            }
        }

        $sql = 'CREATE TABLE ' . $this->db->quote($table->name) . " (\n    " . implode(",\n    ", $lines) . "\n)";

        if ($this->driver === 'mysql') {
            $sql .= ' ENGINE=InnoDB DEFAULT CHARSET=utf8mb4';
        }

        return [$sql, ...$this->indexes($table)];
    }

    /** @return list<string> */
    public function alter(Table $table): array
    {
        $name = $this->db->quote($table->name);
        $statements = [];

        foreach ($table->renameColumns as $from => $to) {
            $statements[] = "ALTER TABLE {$name} RENAME COLUMN {$this->db->quote($from)} TO {$this->db->quote($to)}";
        }

        foreach ($table->dropIndexes as $index) {
            $statements[] = 'DROP INDEX ' . $this->db->quote($index) . ($this->driver === 'mysql' ? " ON {$name}" : '');
        }

        foreach ($table->dropColumns as $column) {
            if ($this->driver === 'sqlite') {
                // SQLite refuses to drop an indexed column. Drop the index a foreign key got
                // (or a plain ->index() under the default name) first, so down() undoes up().
                $statements[] = 'DROP INDEX IF EXISTS ' . $this->db->quote("{$table->name}_{$column}_index");
            }

            $statements[] = "ALTER TABLE {$name} DROP COLUMN {$this->db->quote($column)}";
        }

        foreach ($table->columns as $column) {
            $definition = $this->column($column);

            if ($column->references !== null && $this->driver === 'sqlite') {
                // SQLite can't add a constraint to an existing table, only an inline REFERENCES.
                [$refTable, $refColumn, $onDelete] = $column->references;
                $definition .= " REFERENCES {$this->db->quote($refTable)} ({$this->db->quote($refColumn)})" . ($onDelete ? " ON DELETE {$onDelete}" : '');
            }

            $statements[] = "ALTER TABLE {$name} ADD COLUMN {$definition}";

            if ($column->references !== null && $this->driver !== 'sqlite') {
                $statements[] = "ALTER TABLE {$name} ADD CONSTRAINT "
                    . $this->db->quote("{$table->name}_{$column->name}_foreign") . ' ' . $this->foreignKey($column);
            }
        }

        return [...$statements, ...$this->indexes($table)];
    }

    public function column(Column $column): string
    {
        $sql = $this->db->quote($column->name) . ' ' . $this->type($column);

        if ($column->type === 'id') {
            return $sql;
        }

        $sql .= $column->nullable ? ' NULL' : ' NOT NULL';

        if ($column->useCurrent) {
            $sql .= ' DEFAULT CURRENT_TIMESTAMP';
        } elseif ($column->hasDefault) {
            $sql .= ' DEFAULT ' . $this->literal($column->default);
        }

        if ($column->primary) {
            $sql .= ' PRIMARY KEY';
        }

        if ($column->unique) {
            $sql .= ' UNIQUE';
        }

        if ($column->check !== null) {
            $sql .= " CHECK ({$column->check})";
        }

        return $sql;
    }

    private function type(Column $column): string
    {
        $d = $this->driver;

        return match ($column->type) {
            'id' => match ($d) {
                'sqlite' => 'INTEGER PRIMARY KEY AUTOINCREMENT',
                'mysql' => 'BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY',
                default => 'BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY',
            },
            'foreignId' => match ($d) {
                'sqlite' => 'INTEGER',
                'mysql' => 'BIGINT UNSIGNED',
                default => 'BIGINT',
            },
            'string' => "VARCHAR({$column->args['length']})",
            'text' => 'TEXT',
            'longText' => $d === 'mysql' ? 'LONGTEXT' : 'TEXT',
            'integer' => 'INTEGER',
            'bigInteger' => 'BIGINT',
            'boolean' => match ($d) {
                'sqlite' => 'INTEGER',
                'mysql' => 'TINYINT(1)',
                default => 'BOOLEAN',
            },
            'decimal' => "DECIMAL({$column->args['precision']}, {$column->args['scale']})",
            'date' => 'DATE',
            'timestamp' => match ($d) {
                'sqlite' => 'TEXT',
                'mysql' => 'DATETIME',
                default => 'TIMESTAMP(0)',
            },
            'json' => match ($d) {
                'sqlite' => 'TEXT',
                'mysql' => 'JSON',
                default => 'JSONB',
            },
            default => throw new \InvalidArgumentException("Unknown column type [{$column->type}]."),
        };
    }

    private function foreignKey(Column $column): string
    {
        [$table, $refColumn, $onDelete] = $column->references;

        return "FOREIGN KEY ({$this->db->quote($column->name)}) REFERENCES {$this->db->quote($table)} ({$this->db->quote($refColumn)})"
            . ($onDelete !== null ? " ON DELETE {$onDelete}" : '');
    }

    /** @return list<string> */
    private function indexes(Table $table): array
    {
        $indexes = $table->indexes;

        foreach ($table->columns as $column) {
            if ($column->index !== null) {
                $indexes[] = ['columns' => [$column->name], 'name' => $column->index ?: "{$table->name}_{$column->name}_index", 'unique' => false];
            } elseif ($this->needsForeignKeyIndex($table, $column)) {
                $indexes[] = ['columns' => [$column->name], 'name' => "{$table->name}_{$column->name}_index", 'unique' => false];
            }
        }

        return array_map(
            fn (array $index) => sprintf(
                'CREATE %sINDEX %s ON %s (%s)',
                $index['unique'] ? 'UNIQUE ' : '',
                $this->db->quote($index['name']),
                $this->db->quote($table->name),
                implode(', ', array_map($this->db->quote(...), $index['columns'])),
            ),
            $indexes,
        );
    }

    /**
     * SQLite and Postgres don't index foreign key columns, so every "rows of this parent" lookup
     * (WHERE quote_id = ?) and every cascade/restrict check on the parent scans the whole table.
     * MySQL creates the index itself. Skipped when an index already starts with the column.
     */
    private function needsForeignKeyIndex(Table $table, Column $column): bool
    {
        if ($column->references === null || !$column->indexForeignKey || $this->driver === 'mysql' || $column->unique || $column->primary) {
            return false;
        }

        foreach ($table->indexes as $index) {
            if ($index['columns'][0] === $column->name) {
                return false;
            }
        }

        return true;
    }

    private function literal(mixed $value): string
    {
        return match (true) {
            $value === null => 'NULL',
            is_bool($value) => $this->driver === 'pgsql' ? ($value ? 'TRUE' : 'FALSE') : ($value ? '1' : '0'),
            is_int($value), is_float($value) => (string) $value,
            default => "'" . str_replace(
                $this->driver === 'mysql' ? ['\\', "'"] : ["'"],
                $this->driver === 'mysql' ? ['\\\\', "''"] : ["''"],
                (string) $value,
            ) . "'",
        };
    }
}
